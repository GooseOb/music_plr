fn ar_tracks(n: usize) -> String {
    let form = if n == 0 {
        0
    } else if n == 2 {
        2
    } else if (3..=10).contains(&n) {
        3
    } else if (11..=99).contains(&n) {
        4
    } else {
        let m = n % 100;
        if m == 0 {
            4
        } else if m == 2 {
            2
        } else if (3..=10).contains(&m) {
            3
        } else {
            4
        }
    };
    match form {
        0 => String::from("0 أغنية"),
        2 => format!("{n} أغنيتان"),
        3 => format!("{n} أغاني"),
        _ => format!("{n} أغنية"),
    }
}
