fn be_tracks(n: usize) -> String {
    let m10 = n % 10;
    let m100 = n % 100;
    if m10 == 1 && m100 != 11 {
        format!("{n} трэк")
    } else if (2..=4).contains(&m10) && !(12..=14).contains(&m100) {
        format!("{n} трэкі")
    } else {
        format!("{n} трэкаў")
    }
}
